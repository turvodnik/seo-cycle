#!/usr/bin/env python3
"""T-089 round 2 — the static half of finding C's fix.

`seo_cycle_core.spend_guard`'s runtime gate (PAID_HOSTS + armed_spend())
stops a call to an ALREADY-REGISTERED paid host. It cannot, by construction,
stop a call to a host nobody has told it about yet — that is not a bug to
patch, it is what "the gate lives on data, not on omniscience" means (see
`spend_guard.py`'s module docstring for the full, honest statement of what
the runtime check does and does not guarantee).

This test is the other half: a closed-world inventory. It scans every
`http(s)://` literal in `scripts/*.py` and requires EVERY hostname found —
paid or free — to be consciously sorted into `spend_guard.PAID_HOSTS` or
`FREE_HOSTS` below. A brand-new script hitting a brand-new host fails THIS
test at review/CI time, by name, with the file and host named in the
failure message — it does not need someone to notice a missing gate at
runtime, and it does not need the new host to already be known.

This is deliberately not clever: a regex over string literals, not an AST
walk with control-flow analysis, and it flags a URL mentioned in a
docstring or comment exactly like one used in a real call site (over-count,
not under-count — a host in a comment just needs classifying once too,
same as a real one; it is never silently skipped). That is the honest
trade of a static safety net: it cannot verify a call actually happens, but
it cannot let an unclassified host pass unnoticed either.
"""

from __future__ import annotations

import pathlib
