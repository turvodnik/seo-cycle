import sys
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
sys.path.insert(0, str(SCRIPTS))

from seo_cycle_core.spend_guard import PAID_HOSTS  # noqa: E402

_URL_RE = re.compile(r"https?://([A-Za-z0-9_.\-]+)", re.IGNORECASE)

# Every non-paid host any script in this repo mentions, as of this ticket —
