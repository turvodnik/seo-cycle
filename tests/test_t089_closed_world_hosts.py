def _scan_hosts() -> dict[str, set[str]]:
    """host -> set of relative file paths mentioning it."""
    found: dict[str, set[str]] = {}
    for path in sorted(SCRIPTS.rglob("*.py")):
        text = path.read_text(encoding="utf-8", errors="replace")
        for match in _URL_RE.finditer(text):
            raw = match.group(1).lower()
            host = raw.rstrip(".") or raw  # "..." placeholder rstrips to "" — keep it as-is
            found.setdefault(host, set()).add(str(path.relative_to(ROOT)))
    return found


class ClosedWorldHostsTest(unittest.TestCase):
    def test_registries_do_not_overlap(self) -> None:
        overlap = PAID_HOSTS & FREE_HOSTS
        self.assertFalse(overlap, f"хосты не могут быть одновременно платными и свободными: {overlap}")

    def test_every_host_mentioned_in_scripts_is_classified(self) -> None:
        found = _scan_hosts()
        known = PAID_HOSTS | FREE_HOSTS
        unclassified = {host: files for host, files in found.items() if host not in known}
        if unclassified:
            lines = [f"  {host}: {sorted(files)}" for host, files in sorted(unclassified.items())]
            self.fail(
                "Найдены хосты, не отнесённые ни к PAID_HOSTS "
                "(scripts/seo_cycle_core/spend_guard.py), ни к FREE_HOSTS "
                "(этот файл) — classify them (add to whichever registry is correct):\n"
                + "\n".join(lines)
            )

    def test_all_registered_paid_hosts_are_still_mentioned_somewhere(self) -> None:
        """Symmetric sanity check: a PAID_HOSTS entry nobody's code actually
        contacts anymore is dead weight worth noticing, not silently kept
        forever (not a correctness requirement — informational)."""
        found = _scan_hosts()
        stale = PAID_HOSTS - set(found)
        # Informational only: fail loudly enough to be seen, but this is not
        # a security property, so keep it a plain assertion the way any
        # other "keep the registry tidy" check would be.
        self.assertFalse(stale, f"PAID_HOSTS содержит хосты, которых больше нет в scripts/: {stale} "
                                f"(не баг безопасности — но лишний список гниёт молча, если не смотреть)")

    def test_scan_actually_finds_something(self) -> None:
        """Positive control: the regex itself must be capable of finding a
        host — a scanner that always returns empty would make every test
        above vacuously pass."""
        found = _scan_hosts()
        self.assertIn("api.dataforseo.com", found)
        self.assertGreater(len(found), 50)


